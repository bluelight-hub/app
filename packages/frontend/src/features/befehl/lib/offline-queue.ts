import { useCallback, useEffect, useRef, useState } from 'react';

import { logger } from '@/shared/lib/logger';
import { toast } from 'sonner';

/** Offline Queue Entry */
export interface OfflineQueueEntry {
  key?: number; // auto-generated by IndexedDB
  data: unknown;
  createdAt: string;
}

const DB_NAME = 'befehl-hub';
const STORE_NAME = 'offline-queue';
const DB_VERSION = 2;

/** Singleton DB Connection */
let dbPromise: Promise<IDBDatabase> | null = null;

function getDb(): Promise<IDBDatabase> {
  if (!dbPromise) {
    dbPromise = new Promise((resolve, reject) => {
      const request = indexedDB.open(DB_NAME, DB_VERSION);
      request.onupgradeneeded = () => {
        const db = request.result;
        // Alten Store löschen falls vorhanden (Schema-Migration von keyPath zu autoIncrement)
        if (db.objectStoreNames.contains(STORE_NAME)) {
          db.deleteObjectStore(STORE_NAME);
        }
        db.createObjectStore(STORE_NAME, { autoIncrement: true });
      };
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => {
        dbPromise = null; // Reset on error so next call retries
        reject(request.error);
      };
    });
  }
  return dbPromise;
}

/** Befehl-Offline-Queue Operationen */
export const befehlOfflineQueue = {
  /** Fügt einen Befehl zur Queue hinzu */
  async enqueue(data: unknown): Promise<void> {
    const db = await getDb();

    return new Promise((resolve, reject) => {
      const tx = db.transaction(STORE_NAME, 'readwrite');
      tx.objectStore(STORE_NAME).add({ data, createdAt: new Date().toISOString() });
      tx.oncomplete = () => {
        logger.debug('[OfflineQueue] Befehl eingereiht');
        resolve();
      };
      tx.onerror = () => reject(tx.error);
    });
  },

  /** Holt und löscht alle Queue-Einträge (FIFO durch autoIncrement garantiert) */
  async dequeueAll(): Promise<OfflineQueueEntry[]> {
    const db = await getDb();

    return new Promise((resolve, reject) => {
      const tx = db.transaction(STORE_NAME, 'readwrite');
      const store = tx.objectStore(STORE_NAME);
      const getAll = store.getAll();

      getAll.onsuccess = () => {
        const entries = getAll.result as OfflineQueueEntry[];
        store.clear();
        tx.oncomplete = () => resolve(entries);
      };

      tx.onerror = () => reject(tx.error);
    });
  },

  /** Leert die Queue */
  async clear(): Promise<void> {
    const db = await getDb();

    return new Promise((resolve, reject) => {
      const tx = db.transaction(STORE_NAME, 'readwrite');
      tx.objectStore(STORE_NAME).clear();
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error);
    });
  },

  /** Anzahl der Queue-Einträge */
  async count(): Promise<number> {
    const db = await getDb();

    return new Promise((resolve, reject) => {
      const tx = db.transaction(STORE_NAME, 'readonly');
      const countReq = tx.objectStore(STORE_NAME).count();
      countReq.onsuccess = () => resolve(countReq.result);
      tx.onerror = () => reject(tx.error);
    });
  },
};

/**
 * Hook für Offline-Synchronisation von Befehlen.
 *
 * Überwacht den Online-Status und replayed gespeicherte
 * Befehle bei Wiederverbindung.
 */
export function useOfflineSync(replayFn: (data: unknown) => Promise<void>): {
  isOnline: boolean;
  pendingCount: number;
  enqueue: (data: unknown) => Promise<void>;
} {
  const [isOnline, setIsOnline] = useState(navigator.onLine);
  const [pendingCount, setPendingCount] = useState(0);
  const replayFnRef = useRef(replayFn);
  replayFnRef.current = replayFn;

  /** Aktualisiert den pendingCount aus IndexedDB */
  const refreshCount = useCallback(async () => {
    try {
      const count = await befehlOfflineQueue.count();
      setPendingCount(count);
    } catch (err) {
      logger.warn('[OfflineQueue] Count-Abfrage fehlgeschlagen', err);
    }
  }, []);

  /** Replayed alle gespeicherten Befehle */
  const replay = useCallback(async () => {
    const entries = await befehlOfflineQueue.dequeueAll();
    if (entries.length === 0) return;

    logger.info(`[OfflineQueue] Replay von ${entries.length} Befehl(en)...`);
    let successCount = 0;

    for (let i = 0; i < entries.length; i++) {
      try {
        await replayFnRef.current(entries[i].data);
        successCount++;
      } catch (err) {
        logger.error('[OfflineQueue] Replay fehlgeschlagen für Entry', i, err);
        // Verbleibende Einträge (inkl. fehlgeschlagenen) zurück in Queue
        const remaining = entries.slice(i);
        for (const entry of remaining) {
          await befehlOfflineQueue.enqueue(entry.data);
        }
        break;
      }
    }

    if (successCount > 0) {
      toast.success(`${successCount} Befehl${successCount > 1 ? 'e' : ''} nachträglich gesendet`);
    }

    await refreshCount();
  }, [refreshCount]);

  /** Befehl zur Queue hinzufügen */
  const enqueue = useCallback(
    async (data: unknown) => {
      await befehlOfflineQueue.enqueue(data);
      await refreshCount();
      logger.info('[OfflineQueue] Befehl offline gespeichert');
    },
    [refreshCount],
  );

  // Online/Offline Event Listener
  useEffect(() => {
    const handleOnline = () => {
      setIsOnline(true);
      logger.info('[OfflineQueue] Wieder online – starte Replay');
      replay();
    };

    const handleOffline = () => {
      setIsOnline(false);
      logger.info('[OfflineQueue] Offline erkannt');
    };

    window.addEventListener('online', handleOnline);
    window.addEventListener('offline', handleOffline);

    // Initial Count laden
    refreshCount();

    return () => {
      window.removeEventListener('online', handleOnline);
      window.removeEventListener('offline', handleOffline);
    };
  }, [replay, refreshCount]);

  return { isOnline, pendingCount, enqueue };
}
